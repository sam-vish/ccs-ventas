#!/usr/bin/env node
/* Usage: node scripts/set-domain.mjs ccsventasorlando.com
   Fills in the production domain everywhere it's needed (Step 5.2–5.4):
   canonical (per-path, /es self-canonical), hreflang en/es/x-default, absolute og:image/og:url,
   JSON-LD url, sitemap.xml host, robots.txt Sitemap line. Safe to re-run with a new domain.
   NEVER pass the DealerCenter domain (www.ccsventascars.com) while DealerCenter still hosts it. */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const arg = (process.argv[2] || '').trim().replace(/^https?:\/\//, '').replace(/\/+$/, '');
if (!/^[a-z0-9.-]+\.[a-z]{2,}$/i.test(arg)) { console.error('Usage: node scripts/set-domain.mjs example.com'); process.exit(1); }
if (/(^|\.)ccsventascars\.com$/i.test(arg)) {
  console.error('Refusing: ccsventascars.com is still the DealerCenter site. See MASTER_PROMPT section 3.');
  process.exit(1);
}
const base = 'https://' + arg;
const f = p => join(root, p);

let html = readFileSync(f('index.html'), 'utf8');
const seo = `<!-- SEO:BEGIN (generated by scripts/set-domain.mjs) -->
<link rel="alternate" hreflang="en" href="${base}/">
<link rel="alternate" hreflang="es" href="${base}/es">
<link rel="alternate" hreflang="x-default" href="${base}/">
<meta property="og:url" content="${base}/">
<script>(function(){var l=document.createElement('link');l.rel='canonical';l.href='${base}'+(/^\\/es\\/?$/.test(location.pathname)?'/es':'/');document.head.appendChild(l);})();</script>
<!-- SEO:END -->`;
html = /<!-- SEO:BEGIN[\s\S]*?SEO:END -->/.test(html)
  ? html.replace(/<!-- SEO:BEGIN[\s\S]*?SEO:END -->/, seo)
  : html.replace(/<!-- CANONICAL:[^\n]*-->/, seo);
html = html.replace(/<meta property="og:image" content="[^"]*">/, `<meta property="og:image" content="${base}/og.jpg">`);
html = html.replace(/("@type": "AutoDealer",\s*"name": "[^"]*",\s*"url": )"[^"]*"/, `$1"${base}/"`);
writeFileSync(f('index.html'), html);

writeFileSync(f('sitemap.xml'), readFileSync(f('sitemap.xml'), 'utf8')
  .replace(/<!-- Placeholder host[^\n]*-->\n/, '')
  .replace(/https:\/\/[a-z0-9.-]+(?=\/)/gi, m => m.includes('sitemaps.org') || m.includes('w3.org') ? m : base));

writeFileSync(f('robots.txt'), `User-agent: *\nAllow: /\nDisallow: /api/\n\nSitemap: ${base}/sitemap.xml\n`);
console.log('Domain set to', base);
